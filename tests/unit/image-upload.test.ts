import { describe, expect, it } from "vitest";
import { detectImageType } from "../../lib/domain/image-upload";

describe("image upload validation", () => {
  it.each([
    ["JPEG", [0xff, 0xd8, 0xff, 0xe0, 0xff, 0xd9], "image/jpeg"],
    [
      "PNG",
      [
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
        0x00, 0x00, 0x00, 0x00,
        0x49, 0x45, 0x4e, 0x44,
        0xae, 0x42, 0x60, 0x82,
      ],
      "image/png",
    ],
    ["GIF87a", [0x47, 0x49, 0x46, 0x38, 0x37, 0x61, 0x3b], "image/gif"],
    ["GIF89a", [0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x3b], "image/gif"],
    [
      "WebP",
      [0x52, 0x49, 0x46, 0x46, 0x04, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50],
      "image/webp",
    ],
  ])("recognises a structurally complete %s file", (_, bytes, expected) => {
    expect(detectImageType(Uint8Array.from(bytes as number[]))).toBe(expected);
  });

  it.each([
    ["an executable", [0x4d, 0x5a, 0x90, 0x00]],
    ["HTML disguised as an image", Array.from(new TextEncoder().encode("<script>alert(1)</script>"))],
    ["a JPEG with appended data", [0xff, 0xd8, 0xff, 0xe0, 0xff, 0xd9, 0x41]],
    ["a truncated PNG", [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]],
    ["a WebP with an invalid declared size", [0x52, 0x49, 0x46, 0x46, 0xff, 0, 0, 0, 0x57, 0x45, 0x42, 0x50]],
  ])("rejects %s", (_, bytes) => {
    expect(detectImageType(Uint8Array.from(bytes as number[]))).toBeNull();
  });
});
